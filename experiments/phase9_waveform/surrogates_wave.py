"""
Phase 9 Part B: embedding and surrogates for pseudo-periodic (waveform) signals.

Embedding (B1, predeclared): delay tau = first local minimum of the time-delayed mutual information
(fp.time_delayed_mutual_information / fp.find_optimal_tau, 16 bins; Fraser & Swinney 1986 as
implemented in the project's pipeline); dimension m = Cao's method (fp.cao_method, E1 saturation,
tol 0.05), capped at M_CAP = 10.

Surrogates (B2):
- PPS, pseudo-periodic surrogates (Small M, Yu D, Harrison RG, PRL 87:188101 (2001); blocked; algorithm
  as in the open implementation TimeseriesSurrogates.jl (src/methods/pseudoperiodic.jl) and restated
  in Luo, Nakamura & Small, arXiv:nlin/0404054): delay vectors z_t; s_1 = a random z; repeatedly
  choose j with probability proportional to exp(-||z_j - s_i|| / rho) and set s_{i+1} = z_{j+1}; the
  surrogate is the first coordinate of s.  Noise radius rho: Small et al.'s rule as implemented in
  TimeseriesSurrogates.jl noiseradius(): over a grid of rho, the value maximizing the number of
  length-2 segments shared by data and surrogate that are not part of a shared length-3 segment
  (the implementation notes the paper's ambiguity).
  NULL HYPOTHESIS: the data are a (noisy) periodic orbit with uncorrelated noise: the intra-cycle
  waveform is kept, and the sequence of cycles carries no dependence beyond what a periodic orbit
  plus independent noise produces.  It does NOT allow correlated cycle-to-cycle variability (e.g.
  correlated heart-rate variability), which it can therefore reject without any chaos.
- CS, cycle-shuffled surrogates (Theiler J, Phys Lett A 196:335 (1995); blocked; described in
  Schreiber & Schmitz, Physica D 142:346 (2000), arXiv:chao-dyn/9909037, and Luo et al. 2004): the
  signal is cut into cycles at a fiducial point and the cycles are randomly permuted.  Fiducial
  (predeclared): the R peaks (the beat times used for the window).  The analysed data and every
  surrogate span the first to the last cut point.
  NULL HYPOTHESIS: cycles are exchangeable (independent and identically distributed in order): any
  ordering of the observed cycles is equally likely; intra-cycle structure is arbitrary.  It does
  NOT allow any cycle-to-cycle dependence, deterministic or stochastic (e.g. correlated HRV).
- TS, twin surrogates (Thiel M, Romano MC, Kurths J, Rolfs M, Kliegl R, Phil Trans R Soc A 366:545
  (2008), open postprint; EPL 75:535 (2006)): recurrence matrix R_ij = 1 if ||x_i - x_j||_max <= delta;
  twins are points with identical columns of R; the surrogate starts at a random point and moves to
  the successor of the current point or, if it has twins, of a randomly chosen member of its twin
  set (itself included).  delta (predeclared): recurrence rate 0.05 (Marwan 2011's adaptive rule).
  NULL HYPOTHESIS: the data are generated by the same dynamical system (a first-order Markov chain on
  the recurrence-defined states) started from different initial conditions.  Chaos is part of this
  null, so TS cannot provide evidence of chaos; they are used for testing coupling/synchronization.

Test statistic for B4 (predeclared): nonlinear prediction error at short horizons h (local average of
the k = 5 nearest neighbours, Euclidean, Theiler window = one mean cycle in samples), normalized by
the SD; one-sided: the data are more predictable than the surrogates.
"""
from __future__ import annotations

import math

import numpy as np
from numba import njit
from scipy.spatial import cKDTree

M_CAP = 10


def embed_fwd(x, m, tau):
    n = len(x) - (m - 1) * tau
    return np.ascontiguousarray(np.stack([x[k * tau:k * tau + n] for k in range(m)], axis=1))


def choose_embedding(x, max_tau=60):
    import final_pipeline as fp
    mi = fp.time_delayed_mutual_information(np.asarray(x, float), max_tau=max_tau, n_bins=16)
    tau = int(fp.find_optimal_tau(mi))
    m = int(fp.cao_method(np.asarray(x, float), tau, max_dim=M_CAP + 1, tol=0.05)[0])
    return max(1, tau), int(min(max(m, 2), M_CAP))


# ------------------------------------------------------------------------------------------ PPS
@njit(cache=True)
def _pps(z, rho, start, u):
    n, m = z.shape
    N = n + (m - 1)            # output length = original length when z came from embed_fwd with tau
    out_idx = np.empty(n, dtype=np.int64)
    cur = start
    w = np.empty(n - 1)
    for i in range(n):
        out_idx[i] = cur
        if i == n - 1:
            break
        tot = 0.0
        for t in range(n - 1):
            d = 0.0
            for k in range(m):
                q = z[t, k] - z[cur, k]
                d += q * q
            w[t] = math.exp(-math.sqrt(d) / rho)
            tot += w[t]
        r = u[i] * tot
        acc = 0.0
        j = n - 2
        for t in range(n - 1):
            acc += w[t]
            if acc >= r:
                j = t
                break
        cur = j + 1
    return out_idx


def pps(x, m, tau, rho, rng, shift=True):
    """One PPS surrogate of length len(x) - (m-1) tau (first coordinate of the surrogate vectors)."""
    z = embed_fwd(np.asarray(x, float), m, tau)
    start = int(rng.integers(0, len(z))) if shift else 0
    idx = _pps(z, float(rho), start, rng.random(len(z)))
    return z[idx, 0]


def noise_radius(x, m, tau, rhos, rng, n_rep=1):
    """Small et al.'s rule (TimeseriesSurrogates.jl noiseradius): argmax over rho of the number of
    length-2 segments of the surrogate equal to a length-2 segment of the data at the same position
    pair that are not extended to length 3."""
    x = np.asarray(x, float)
    z = embed_fwd(x, m, tau)
    xs = z[:, 0]
    counts = np.zeros(len(rhos))
    # index-based equality: surrogate value s[j] equals data x[i] iff it is the same embedded point
    for _ in range(n_rep):
        for k, rho in enumerate(rhos):
            idx = _pps(z, float(rho), int(rng.integers(0, len(z))), rng.random(len(z)))
            # surrogate consecutive pairs (idx[j], idx[j+1]) that follow the data (idx[j]+1 == idx[j+1])
            # but whose continuation does not (idx[j+1]+1 != idx[j+2])
            a = idx[:-2]
            b = idx[1:-1]
            c = idx[2:]
            counts[k] += np.sum((b == a + 1) & (c != b + 1))
    return float(rhos[int(np.argmax(counts))]), counts


# ------------------------------------------------------------------------------- cycle shuffle
def cycle_shuffle(x, cuts, rng):
    """Cycles x[cuts[k]:cuts[k+1]] randomly permuted; returns (surrogate, data span x[cuts[0]:cuts[-1]])."""
    x = np.asarray(x, float)
    cyc = [x[cuts[k]:cuts[k + 1]] for k in range(len(cuts) - 1)]
    order = rng.permutation(len(cyc))
    return np.concatenate([cyc[o] for o in order]), x[cuts[0]:cuts[-1]]


# ------------------------------------------------------------------------------ twin surrogates
def twin_sets(z, rr=0.05):
    """Recurrence matrix at recurrence rate rr (max norm) and twin groups (identical columns)."""
    n = len(z)
    tree = cKDTree(z)
    # adaptive delta: rr quantile of pairwise max-norm distances, estimated from a random subset
    rng = np.random.default_rng(0)
    sub = rng.choice(n, size=min(n, 1500), replace=False)
    d = np.max(np.abs(z[sub][:, None, :] - z[sub][None, :, :]), axis=2)
    delta = float(np.quantile(d[np.triu_indices(len(sub), 1)], rr))
    nbrs = tree.query_ball_point(z, delta, p=np.inf)
    keys = {}
    for i, nb in enumerate(nbrs):
        keys.setdefault(tuple(sorted(nb)), []).append(i)
    group = np.empty(n, dtype=object)
    for members in keys.values():
        arr = np.array(members)
        for i in members:
            group[i] = arr
    return group, delta


def twin_surrogate(z, group, rng, length=None):
    n = len(z)
    length = n if length is None else length
    cur = int(rng.integers(0, n - 1))
    out = np.empty(length, dtype=np.int64)
    for i in range(length):
        out[i] = cur
        g = group[cur]
        nxt = int(rng.choice(g)) + 1 if len(g) > 1 else cur + 1
        if nxt >= n:                  # end of data: restart at a random point (Thiel et al. footnote-free choice)
            nxt = int(rng.integers(0, n - 1))
        cur = nxt
    return out


# ----------------------------------------------------------------------------- NLP statistic
def nlp_error(x, m, tau, h=1, k=5, theiler=None):
    """Normalized leave-one-out local-average prediction error at horizon h (Euclidean kNN)."""
    x = np.asarray(x, float)
    z = embed_fwd(x, m, tau)
    n = len(z) - h
    Z = z[:n]
    target = x[(m - 1) * tau + h:(m - 1) * tau + h + n]
    theiler = (m - 1) * tau if theiler is None else theiler
    tree = cKDTree(Z)
    kk = min(n, k + 2 * theiler + 2)
    _, idx = tree.query(Z, k=kk)
    pred = np.empty(n)
    for i in range(n):
        nb = [j for j in idx[i] if abs(j - i) > theiler][:k]
        pred[i] = target[nb].mean() if nb else target.mean()
    return float(np.sqrt(np.mean((target - pred) ** 2)) / max(np.std(x), 1e-12))


# ------------------------------------------------------------------- correlation dimension statistic
def corr_dim(x, m, tau, theiler, c_lo=1e-3, c_hi=5e-2):
    """Grassberger-Procaccia correlation dimension: least-squares slope of ln C_m(eps) vs ln eps over the
    eps values with C_m in [c_lo, c_hi] (max norm, Theiler window), on the standardized series.  Used
    to verify PPS / CS against the published behaviour (Small et al. 2001 and Luo et al. 2004 used the
    correlation dimension as test statistic)."""
    from experiments.phase9_waveform import measures as M
    eps = np.geomspace(1e-3, 3.0, 80)
    e, C = M.correlation_sums(x, m_max=m, L=tau, eps=eps, theiler=theiler)
    c = C[m - 1]
    sel = (c >= c_lo) & (c <= c_hi)
    if sel.sum() < 3:
        return float("nan")
    return float(np.polyfit(np.log(e[sel]), np.log(c[sel]), 1)[0])
