"""
Phase 9 Part A: RR sources with per-beat types ('N' normal, 'V' ventricular ectopic,
'A' atrial ectopic).  A window of n intervals has n + 1 beats; interval i runs from beat i to
beat i + 1, so a premature interval i (Phase 5/6/8 convention) ends at ectopic beat i + 1.

Sources
- NULLS: the 17 Phase 5-6 PASS nulls (N1-N6, S1, S2 5 / 10 %, E1, E2, E3 5 / 10 %, E4,
  E5 5 / 10 %, E6), generated by the unchanged Phase 5/6 code at window length n
  (experiments.phase8_cardiac.nulls.length).  Ectopic beat positions are recovered by
  re-executing the Phase 6 Part B ectopy draws (same RNG streams, same calls) and the RR series is
  asserted to be identical to the Phase 6 generator's output.  Types: S2, E1-E4, E6 'V'
  (ventricular-type, full compensatory pause); E5 'A' (atrial-type, sinus reset).
- MODELS: every Phase 8 regime (results/ground_truth/regimes.json, labels and split unchanged).
  Clean model RR (Phase 8 series.model_rr with Phase 8's seed scheme) is rescaled linearly to
  mean 0.8 s with its coefficient of variation kept (all families; predeclared, so that every
  synthetic ECG has a physiological mean rate: Phase 8 kept the AV node (~0.18 s) and coupled vdP
  (0.24-0.67 s) in native seconds).  Optional ectopy (Phase 8 series._ectopy: S2_5, E1,
  E3_10, all 'V') is inserted into the clean rescaled RR with a Phase 9 RNG stream.
- KTZ (A2 morphology family, model ktz.py): paced input at RR0 = 0.8 s, i.e. one time step =
  0.8 / P_nom s; optional ectopy as for MODELS; KTz pacing periods P_k = round(RR_k / step) ts;
  the window's RR is P_k * step (so RR and APD are on the same time grid).
"""
from __future__ import annotations

import json
import pathlib

import numpy as np

from experiments.phase5_rr import config as C5
from experiments.phase5_rr import systems as S5
from experiments.phase6_robust import config as C6
from experiments.phase6_robust import systems as S6
from experiments.phase8_cardiac import nulls as NL8
from experiments.phase8_cardiac import series as SR8

HERE = pathlib.Path(__file__).resolve().parent
ENTROPY9 = 20261002
RR_MEAN = 0.8
NULLS = NL8.PASS_NULLS
NULL_TYPE = {c: ("V" if c.startswith(("S2", "E1", "E2", "E3", "E4", "E6")) else
                 "A" if c.startswith("E5") else None) for c in NULLS}
ECTOPY = ("S2_5", "E1", "E3_10")
ECT_CODE = {"none": 0, "S2_5": 1, "E1": 2, "E3_10": 3}
FAMILY9 = {"mackey_glass": 1, "phase_reset": 2, "coupled_vdp": 3, "av_node": 4, "ktz": 5, "null": 6}


def ss9(*key):
    return np.random.SeedSequence([ENTROPY9, *[int(k) for k in key]])


# ------------------------------------------------------------------------------------- nulls
def _phase6_starts(condition, seed):
    """Re-execute experiments.phase6_robust.systems.ectopy's draws for a Part B ectopy null and
    return (x_unquantized, list of premature interval indices).  Must be called inside
    NL8.length(n)."""
    kind, params = C6.PARTB[condition][1], C6.PARTB[condition][2]
    p5 = S5.parts("N1_linear_rr", seed)
    x = p5["unquantized"].copy()
    n = len(x)
    labels = np.zeros(n, dtype=bool)
    rng = S6._rng(condition, seed)
    prem = []
    if kind in ("bigeminy", "trigeminy"):
        period = 2 if kind == "bigeminy" else 3
        s = int(rng.integers(1, period + 1))
        for i in range(s, n - 1, period):
            S6._apply_group(x, labels, i, 1, rng)
            prem.append(i)
    elif kind == "couplets":
        m = int(round(params["rate"] * n / 2))
        for i in S6._place_groups(rng, [3] * m, n):
            S6._apply_group(x, labels, i, 2, rng)
            prem += [i, i + 1]
    elif kind == "runs":
        n_runs = int(rng.integers(C6.RUN_COUNT_RANGE[0], C6.RUN_COUNT_RANGE[1] + 1))
        lengths = [int(rng.integers(C6.RUN_LENGTH_RANGE[0], C6.RUN_LENGTH_RANGE[1] + 1)) for _ in range(n_runs)]
        starts = S6._place_groups(rng, [k + 1 for k in lengths], n)
        for i, k in zip(starts, lengths):
            cyc = list(rng.uniform(*C6.RUN_CYCLE_RANGE_S, size=k - 1))
            S6._apply_group(x, labels, i, k, rng, run_cycle=cyc)
            prem += list(range(i, i + k))
    elif kind == "atrial":
        m = int(round(params["rate"] * n))
        for i in S6._place_groups(rng, [2] * m, n):
            c = rng.uniform(*C6.PREMATURE_COUPLING_RANGE)
            d = rng.uniform(*C6.ATRIAL_POST_FACTOR_RANGE)
            x[i] = c * x[i]
            x[i + 1] = d * x[i + 1]
            prem.append(i)
    elif kind == "s2_trend":
        mr_t = np.random.default_rng(S5._ss(C5.COND_CODE["N3_linear_rr_trend"], seed))
        x, _ = S5.add_trend(x, mr_t, p5["mean_rr"])
        mr_e = np.random.default_rng(S5._ss(C5.COND_CODE["S2_ectopic_10pct"], seed))
        x, pe = S5.add_ectopics(x, mr_e, 0.10)
        prem = list(pe["ectopic_indices"])
    else:
        raise ValueError(kind)
    return x, sorted(prem)


def null_window(condition, seed, n):
    """(rr [s], types[n+1]) for a Phase 5-6 PASS null; rr identical to Phase 8 nulls.generate."""
    with NL8.length(n):
        rr = np.asarray(S6.generate(condition, seed), float)
        prem = []
        if condition in C6.PARTB:
            x, prem = _phase6_starts(condition, seed)
            if not np.array_equal(S5.quantize(x), rr):
                raise AssertionError(f"ectopy replay differs from Phase 6 generator: {condition} {seed}")
        elif condition.startswith("S2_"):
            prem = list(S5.parts(condition, seed)["params"]["ectopic_indices"])
    types = np.array(["N"] * (n + 1), dtype="<U1")
    for i in prem:
        types[i + 1] = NULL_TYPE[condition]
    return rr, types


# ------------------------------------------------------------------------------------ models
def load_regimes():
    return json.load(open(HERE.parent / "phase8_cardiac" / "results" / "ground_truth" / "regimes.json"))


def _insert_ectopy(x, ectopy, rng):
    x = np.asarray(x, float)
    types = np.array(["N"] * (len(x) + 1), dtype="<U1")
    if ectopy == "none":
        return x, types
    x2, prem = SR8._ectopy(x, ectopy, rng)
    for i in prem:
        types[i + 1] = "V"
    return x2, types


def model_window(family, regime_idx, params, n, ectopy, seed):
    """Clean Phase 8 model RR (seed scheme of experiments.phase8_cardiac.series, variant i_clean),
    rescaled to mean RR_MEAN with CV kept, plus optional ectopy.  Returns (rr, types, info)."""
    fc = SR8.FAMILY_CODE[family]
    clean = SR8.model_rr(family, params, n, np.random.default_rng(SR8.ss(fc, regime_idx, n, 0, seed)))
    scale = RR_MEAN / float(np.mean(clean))
    x = clean * scale
    rr, types = _insert_ectopy(x, ectopy, np.random.default_rng(ss9(FAMILY9[family], regime_idx, n,
                                                                         ECT_CODE[ectopy], seed)))
    return rr, types, {"native_mean_rr": float(np.mean(clean)), "rescale": scale}


# --------------------------------------------------------------------------------------- KTz
def ktz_input(P_nom, ectopy, n_beats, rng):
    """Integer KTz pacing periods (ts) for a paced input at RR_MEAN with optional ectopy, and
    the per-beat types (length n_beats + 1)."""
    step = RR_MEAN / P_nom
    x = np.full(n_beats, RR_MEAN)
    x, types = _insert_ectopy(x, ectopy, rng)
    per = np.maximum(np.round(x / step).astype(np.int64), 1)
    return per, types, step


def ktz_window(P_nom, regime_idx, ectopy, n, seed, transient=1000, apd_ref_ts=None):
    """KTz-driven window: (rr [s], types, apd_s [n+1], info).  Initial state: x, y, z ~ U(-0.1, 0.1)
    from the window's seed; the first `transient` beats are discarded."""
    from experiments.phase9_waveform.morph import ktz
    rng = np.random.default_rng(ss9(FAMILY9["ktz"], regime_idx, n, ECT_CODE[ectopy], seed))
    per, types, step = ktz_input(P_nom, ectopy, transient + n + 1, rng)
    x0, y0, z0 = rng.uniform(-0.1, 0.1, size=3)
    apd, *_ = ktz.run(per, x0, y0, z0)
    w = slice(transient, transient + n + 1)
    apd_w = apd[w].copy()
    n_nan = int(np.isnan(apd_w).sum())
    ref = float(np.nanmean(apd[transient:])) if apd_ref_ts is None else float(apd_ref_ts)
    apd_w[np.isnan(apd_w)] = ref                   # no AP (refractory stimulus): T unchanged
    rr = per[transient:transient + n] * step
    return rr, types[w], apd_w * step, {"step_s": step, "apd_ref_s": ref * step, "n_apd_nan": n_nan}
