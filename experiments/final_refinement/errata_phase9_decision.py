"""
Erratum E1: Phase 9 TEST decision tabulated over the 101 preregistered conditions.

    python -m experiments.final_refinement.errata_phase9_decision

PREREGISTRATION.md (Phase 9) Section 4: PASS iff detections <= floor(0.07 N) = 7/100 in EACH of the 101
conditions of null_input, null_real, noncha_input and noncha_real (17 + 17 nulls, 18 + 49 non-chaotic regimes).
A KTz regime is a (pacing period P, input pattern) pair (`results/ground_truth/ktz_labels.json`), but its
window name carries only P, and the frozen `decide9.py` groups by `group|name`; it therefore pooled the 31 KTz
non-chaotic regimes into 11 groups of 100-400 windows (81 conditions). This script repeats the decision with
the preregistered conditions (KTz key = group|name|input), using the same stored per-candidate detection flags
as `decide9.py`, and writes `errata/phase9_decision_101.{md,json}` and `errata/by_condition9_101.csv`.
`decide9.py` and its outputs are left unchanged (the file is frozen by SHA-256 in the preregistration).
"""
from __future__ import annotations

import csv
import json
import math
import pathlib
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "experiments/phase9_waveform/results/test/test9.jsonl"
OUT = pathlib.Path(__file__).resolve().parent / "errata"
PASS_GROUPS = ("null_input", "null_real", "noncha_input", "noncha_real")
CANDIDATES = ("k1_frozen512", "k2_mnlp_ann", "k3_mnlp_growth_ann", "k4_mnlp_growth_rr", "k5_mnlp_fsle_ann")


def main():
    rows = {}
    for line in open(SRC):
        r = json.loads(line)
        rows.setdefault(r["task_id"], r)          # first record per window, as decide9.py
    out = {"rule": "PREREGISTRATION.md (Phase 9) Section 4, 101 conditions; KTz regime = (P, input)",
           "candidates": {}}
    table = []
    for c in CANDIDATES:
        spec = defaultdict(lambda: [0, 0])
        spec81 = defaultdict(lambda: [0, 0])
        prim = 0
        nprim = 0
        for r in rows.values():
            det = bool(((r.get("results") or {}).get(c) or {}).get("detected", False))
            if r["group"] in PASS_GROUPS:
                k81 = r["group"] + "|" + r["name"]
                k = k81 + ("|" + r["ectopy"] if r.get("family") == "ktz" else "")
                spec[k][0] += det
                spec[k][1] += 1
                spec81[k81][0] += det
                spec81[k81][1] += 1
            elif r["group"] == "chaos_primary":
                prim += det
                nprim += 1
        failed = sorted(k for k, (a, n) in spec.items() if a > math.floor(0.07 * n))
        failed81 = sorted(k for k, (a, n) in spec81.items() if a > math.floor(0.07 * n))
        out["candidates"][c] = {"n_conditions": len(spec), "PASS": not failed, "n_failed": len(failed),
                                "failed": failed, "primary_detected": prim, "primary_N": nprim,
                                "pass_pool_detected": sum(v[0] for v in spec.values()),
                                "pass_pool_N": sum(v[1] for v in spec.values()),
                                "decide9_grouping": {"n_conditions": len(spec81), "PASS": not failed81,
                                                     "n_failed": len(failed81)}}
        for k, (a, n) in sorted(spec.items()):
            table.append({"cand": c, "cond": k, "k": a, "N": n, "limit": math.floor(0.07 * n),
                          "within": a <= math.floor(0.07 * n)})
    passing = [c for c in CANDIDATES if out["candidates"][c]["PASS"]]
    winner = sorted(passing, key=lambda c: (-out["candidates"][c]["primary_detected"],
                                            out["candidates"][c]["pass_pool_detected"], CANDIDATES.index(c)))[0]
    out["passing"], out["winner"] = passing, winner
    OUT.mkdir(exist_ok=True)
    json.dump(out, open(OUT / "phase9_decision_101.json", "w"), indent=1)
    with open(OUT / "by_condition9_101.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(table[0]))
        w.writeheader()
        w.writerows(table)
    md = ["# Phase 9 TEST decision over the 101 preregistered conditions (erratum E1)", "",
          "Generated by `python -m experiments.final_refinement.errata_phase9_decision` from "
          "`experiments/phase9_waveform/results/test/test9.jsonl` (stored detection flags, as `decide9.py`). "
          "See `experiments/final_refinement/ERRATA.md` E1.", "",
          f"Passing candidates: {passing}. WINNER: **{winner}**.", "",
          "| candidate | conditions | PASS | failed | primary chaotic | PASS-condition detections | decide9.py grouping "
          "(conditions, PASS, failed) |", "|---|---|---|---|---|---|---|"]
    for c, v in out["candidates"].items():
        g = v["decide9_grouping"]
        md.append(f"| {c} | {v['n_conditions']} | {v['PASS']} | {v['n_failed']} | {v['primary_detected']}/"
                  f"{v['primary_N']} | {v['pass_pool_detected']}/{v['pass_pool_N']} | {g['n_conditions']}, {g['PASS']}, "
                  f"{g['n_failed']} |")
    md += ["", "Failed conditions under the preregistered grouping:", ""]
    for c, v in out["candidates"].items():
        if v["failed"]:
            cells = {x["cond"]: x for x in table if x["cand"] == c}
            md.append(f"- **{c}** ({v['n_failed']}): " + "; ".join(f"{k} {cells[k]['k']}/{cells[k]['N']}"
                                                                   for k in v["failed"]))
    (OUT / "phase9_decision_101.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
