def seg_subject_rates():
    R = uniq(jl(P10 / "conf/seg.jsonl"), "id")
    out = defaultdict(dict)
    for r in R:
        segs = [s for s in r["segments"] if not s["gap"]]
        for arm, okf in (("raw", None), ("masked", "analysable"), ("edited", "eligible"), ("wu", "wu")):
            key = f"TIT_{arm}"
            if arm == "raw":
                use = segs
            elif arm == "wu":
                use = [s for s in segs if s[key].get("eligible", True) and s[key].get("analysable", True)]
            else:
                use = [s for s in segs if s[key].get(okf, False)]
            if use:
                out[(r["subject"], r["group"])][arm] = (np.mean([bool(s[key].get("positive", False)) for s in use]),
                                                         len(use))
    return out


