def wilson(k, n, z=1.959963984540054):
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def rate_row(k, n):
    lo, hi = wilson(k, n)
    return {"k": int(k), "n": int(n), "rate_pct": 100 * k / n if n else np.nan, "ci_lo_pct": 100 * lo,
            "ci_hi_pct": 100 * hi}


def jl(p):
    return [json.loads(line) for line in open(p)]


def uniq(rows, key):
    out = {}
    for r in rows:
        out.setdefault(r[key] if not callable(key) else key(r), r)
    return list(out.values())


def rel(p):
    return str(pathlib.Path(p).relative_to(ROOT))


def save(fig, name):
    FIG.mkdir(exist_ok=True)
    fig.savefig(FIG / f"{name}.pdf", bbox_inches="tight", metadata={"CreationDate": None, "ModDate": None})
    fig.savefig(FIG / f"{name}.png", dpi=300, bbox_inches="tight", metadata={"Software": None})
    plt.close(fig)
    WRITTEN.append(name)


def table(df, name, title, source, note=""):
    TAB.mkdir(exist_ok=True)
    df.to_csv(TAB / f"{name}.csv", index=False, float_format="%.6g")
    md = [f"# {title}", "", f"Source: {source}. Generated by `make_figures.py`; do not edit by hand.", ""]
    if note:
        md += [note, ""]
    cols = list(df.columns)
    md += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append("" if not np.isfinite(v) else (f"{v:.1f}" if c.endswith("_pct") else f"{v:.4g}"))
            else:
                cells.append(str(v))
        md.append("| " + " | ".join(cells) + " |")
    (TAB / f"{name}.md").write_text("\n".join(md) + "\n")


def note(fig, what, source, n, stats_, files):
    NOTES.extend([f"## {fig}", "", f"- **Plotted.** {what}", f"- **Data source.** {source}",
                  f"- **Sample sizes.** {n}", f"- **Statistics.** {stats_}",
                  "- **Result files read.** " + ", ".join(f"`{f}`" for f in files), ""])


def dot_ci(ax, x, y, lo, hi, det, horizontal=True, filled=True, ms=4.2, label=None, color=None, marker=None):
    c = color or COL[det]
    m = marker or MRK[det]
    v = x if horizontal else y
    lo = np.minimum(np.asarray(lo, float), v)          # guard against 1-ulp Wilson rounding at k = 0 or k = n
    hi = np.maximum(np.asarray(hi, float), v)
    if horizontal:
        ax.errorbar(x, y, xerr=[np.subtract(x, lo), np.subtract(hi, x)], fmt="none", ecolor=c, elinewidth=0.9,
                    capsize=0, zorder=2)
    else:
        ax.errorbar(x, y, yerr=[np.subtract(y, lo), np.subtract(hi, y)], fmt="none", ecolor=c, elinewidth=0.9,
                    capsize=0, zorder=2)
    ax.plot(x, y, linestyle="none", marker=m, ms=ms, mfc=c if filled else "white", mec=c, mew=0.9, zorder=3,
            label=label)


def light_grid(ax, axis="x"):
    ax.grid(axis=axis, color=GRID, linewidth=0.5, zorder=0)
    ax.set_axisbelow(True)


