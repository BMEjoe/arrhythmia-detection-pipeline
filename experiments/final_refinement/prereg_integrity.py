"""
Final refinement, Part 2: preregistration integrity from the git history.

    python -m experiments.final_refinement.prereg_integrity     # writes PREREG_INTEGRITY.md

For every preregistration file:
  1. the preregistration commit (the commit that first holds the final, guarded version) and every later commit
     that touched the file;
  2. the diff between the version at the preregistration commit and the current version: MATCH iff every change
     is an addition inside an "Amendment" section (no line of the preregistered text removed or altered);
  3. the first commit that added a confirmatory result file, and whether the preregistration commit is its
     ancestor and earlier in time.
Requires the full git history (`git fetch --unshallow` on a shallow clone).
"""
from __future__ import annotations

import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = pathlib.Path(__file__).resolve().parent / "PREREG_INTEGRITY.md"

# (phase, file, preregistration commit as recorded in the phase report, confirmatory result files)
PREREGS = [
    ("3", "experiments/phase3_lle/PREREGISTRATION.md", "25ec207",
     ["experiments/phase3_lle/results/test/c1_rosenstein_m2_iaaft.jsonl", "experiments/phase3_lle/results/test/baseline.jsonl"]),
    ("4", "experiments/phase4_upo/PREREGISTRATION.md", "a6fe566", ["experiments/phase4_upo/results/test/test.jsonl"]),
    ("5", "experiments/phase5_rr/PREREGISTRATION.md", "03787bf", ["experiments/phase5_rr/results/test/test.jsonl"]),
    ("6", "experiments/phase6_robust/PREREGISTRATION.md", "3325e16", ["experiments/phase6_robust/results/test/test.jsonl"]),
    ("7", "experiments/phase7_mitbih/PREREGISTRATION.md", "fb212da",
     ["experiments/phase7_mitbih/results/run/raw.jsonl", "experiments/phase7_mitbih/results/run/edited.jsonl",
      "experiments/phase7_mitbih/results/run/annotation.jsonl"]),
    ("8", "experiments/phase8_cardiac/PREREGISTRATION.md", "991ede3",
     ["experiments/phase8_cardiac/results/test/test_256.jsonl", "experiments/phase8_cardiac/results/test/test_512.jsonl"]),
    ("9 (Part E)", "experiments/phase9_waveform/PREREGISTRATION.md", "31cd725",
     ["experiments/phase9_waveform/results/test/test9.jsonl"]),
    ("9 (Part F)", "experiments/phase9_waveform/PREREGISTRATION_F.md", "89d4ba9",
     ["experiments/phase9_waveform/results/partf/partf_windows.jsonl"]),
    ("10", "experiments/phase10_final/PREREGISTRATION.md", "8fc7bd9",
     ["experiments/phase10_final/results/conf/data_checks.json", "experiments/phase10_final/results/conf/real.jsonl",
      "experiments/phase10_final/results/conf/seg.jsonl", "experiments/phase10_final/results/conf/spike.jsonl"]),
]


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def commit_info(c):
    h, date, subj = git("show", "-s", "--format=%h%x09%ad%x09%s", "--date=iso-strict", c).strip().split("\t", 2)
    return h, date, subj


def first_added(path):
    out = git("log", "--diff-filter=A", "--format=%h", "--", path).split()
    return out[-1] if out else None


def is_ancestor(a, b):
    return subprocess.run(["git", "merge-base", "--is-ancestor", a, b], cwd=ROOT).returncode == 0


def diff_status(path, c):
    """Compare the preregistered version (at commit c) with the current file. Allowed: text appended at the end
    under an Amendment heading, and an "(none)" placeholder under the Amendments heading replaced by it."""
    old = git("show", f"{c}:{path}").splitlines()
    new = (ROOT / path).read_text().splitlines()
    d = git("diff", "--no-color", "-U0", c, "HEAD", "--", path)
    removed = [l[1:] for l in d.splitlines() if l.startswith("-") and not l.startswith("---")]
    added = [l[1:] for l in d.splitlines() if l.startswith("+") and not l.startswith("+++")]
    heads = [i for i, l in enumerate(old) if re.match(r"#+ .*Amendments", l)]
    placeholder = None
    if heads and removed == ["(none)"]:
        cand = [i for i, l in enumerate(old) if l.strip() == "(none)" and i > heads[-1]]
        placeholder = cand[-1] if cand else None
    base = [l for i, l in enumerate(old) if i != placeholder]
    prefix_kept = new[:len(base)] == base
    tail = new[len(base):] if prefix_kept else []
    real_removed = [l for l in removed if not (placeholder is not None and l.strip() == "(none)")]
    in_amend = prefix_kept and (not tail or bool(heads))
    return {"removed": real_removed, "added": added, "prefix_kept": prefix_kept, "tail": tail,
            "tail_in_amend": in_amend, "n_old": len(base), "n_new": len(new), "placeholder": placeholder is not None}


def main():
    lines = ["# Preregistration integrity (git history)", "",
             "Generated by `python -m experiments.final_refinement.prereg_integrity`. For each preregistration: the "
             "commit that holds the preregistered version, every later commit that touched the file, whether the "
             "current file equals the preregistered text plus appended amendments, and the first commit that added "
             "a confirmatory result file. 'Earlier' means an ancestor commit with an earlier commit time. Push times "
             "are not recorded in git; each runner's guard refused to start unless the file was committed, "
             "unmodified and present on the remote (Phase 3 guard), which is what 'pushed before' rests on.", "",
             "| phase | file | preregistration commit | later commits touching the file | preregistered text unchanged "
             "(only amendments appended) | first confirmatory result commit | prereg earlier (ancestor and time) |",
             "|---|---|---|---|---|---|---|"]
    details = []
    allok = True
    for ph, path, pc, results in PREREGS:
        h, date, subj = commit_info(pc)
        log = git("log", "--follow", "--format=%h%x09%ad%x09%s", "--date=iso-strict", "--", path).strip().splitlines()
        hashes = [l.split("\t")[0] for l in log]
        idx = hashes.index(h) if h in hashes else None
        later = [l.split("\t") for l in log[:idx]] if idx is not None else []
        earlier = [l.split("\t") for l in log[idx + 1:]] if idx is not None else []
        ds = diff_status(path, h)
        unchanged = ds["prefix_kept"] and not ds["removed"] and ds["tail_in_amend"]
        firsts = []
        for rpath in results:
            fa = first_added(rpath)
            if fa:
                firsts.append((commit_info(fa), rpath))
        firsts.sort(key=lambda x: x[0][1])
        (fh, fdate, fsubj), frpath = firsts[0]
        order_ok = is_ancestor(h, fh) and date < fdate
        allok &= unchanged and order_ok
        later_s = "; ".join(f"`{c[0]}` {c[2][:70]}" for c in reversed(later)) or "none"
        lines.append(f"| {ph} | `{path}` | `{h}` {date[:16]} | {later_s} | "
                     f"{'yes' if unchanged else '**NO**'} ({len(ds['removed'])} lines removed or changed, "
                     f"{len(ds['tail'])} amendment lines appended"
                     f"{'; (none) placeholder replaced' if ds['placeholder'] else ''}) | "
                     + "; ".join(f"`{c[0]}` {c[1][:16]} (`{pathlib.Path(rp).name}`)" for c, rp in firsts) + " | "
                     f"{'yes' if order_ok else '**NO**'} |")
        det = [f"### Phase {ph}: `{path}`", "",
               f"- Preregistration commit: `{h}` ({date}) — {subj}",
               f"- Earlier commits of this path (drafts / renames): " +
               ("; ".join(f"`{c[0]}` {c[1][:16]} {c[2][:80]}" for c in reversed(earlier)) or "none"),
               f"- Later commits touching the file: " +
               ("; ".join(f"`{c[0]}` {c[1][:16]} {c[2][:100]}" for c in reversed(later)) or "none"),
               f"- Preregistered text kept verbatim as the file's first {ds['n_old']} lines: "
               f"{'yes' if ds['prefix_kept'] else 'NO'}; lines removed or changed since: {len(ds['removed'])}; "
               f"lines added: {len(ds['added'])} (current length {ds['n_new']}).",
               f"- First confirmatory result commit: `{fh}` ({fdate}) — {fsubj} (`{frpath}`); preregistration "
               f"commit is an ancestor: {is_ancestor(h, fh)}; earlier in time: {date < fdate}."]
        if ds["removed"]:
            det.append("- Removed or changed lines:")
            det += [f"  - `{l[:150]}`" for l in ds["removed"][:20]]
        if ds["tail"]:
            heads = [l for l in ds["tail"] if l.startswith("#")]
            det.append("- Headings of the appended text: " + ("; ".join(f"`{l}`" for l in heads) or "(none)"))
        details += det + [""]
    lines += ["", f"**All preregistrations intact and earlier than their first confirmatory result: "
                  f"{'yes' if allok else 'NO'}.**", "", "## Details", ""] + details
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:20]))
    print("ALL OK" if allok else "NOT ALL OK")


if __name__ == "__main__":
    main()
